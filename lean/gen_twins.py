#!/usr/bin/env python3
"""gen_twins.py <qc_dec.h> <out.lean>: the Lean twin of each generated record decoder (qc/gen_decoders.py's output).

Reads the generated C itself, not the generator: each decoder must be, statement for statement, the header check, then
per column `if (h >= he) return 0;` and one of the three column blocks (NULL, INTEGER, TEXT) for that column's index,
then the end check. Anything else is an error (the twins, and so their proofs, would no longer describe the C). Each
twin is genStart, one genCol per column and genEnd (lean/Turbo/Record.lean), with a proof that it is decodeFast for
its shape; decodeFast_sound proves that sound against OP_Column."""
import re, sys

HEAD = ['u32 hl = rec[0]; if (hl >= 0x80 || hl > sz) return 0;',
        'const u8 *h = rec + 1, *he = rec + hl, *d = rec + hl;']
GUARD = 'if (h >= he) return 0;'
END = 'return h < he ? d <= rec + sz : d == rec + sz;'

def block(c, k):   # the statements a column of class c (index k) must be
    if c == 'N':
        return ['if (*h++ != 0) return 0;', f'cols[{k}].type = SQLITE_NULL;']
    if c == 'I':
        return ['{ u32 t = *h++; if (t == 0 || t == 7 || t > 9) return 0;',
                f'cols[{k}].type = SQLITE_INTEGER; cols[{k}].i = qc_int(t, d); d += qc_iw[t]; }}']
    return ['{ u32 t = *h++; if (t >= 0x80) { if (h >= he || (*h & 0x80)) return 0; t = ((t & 0x7f) << 7) | *h++; }',
            'if (t < 13 || !(t & 1)) return 0;',
            f'u32 len = (t - 13) >> 1; cols[{k}].type = SQLITE_TEXT; cols[{k}].z = d; cols[{k}].n = (int)len; d += len; }}']

def main(src, out):
    text = open(src).read()
    fns = re.findall(r'static int (qc_dec_([NIT]+))\(const u8 \*rec, u32 sz, QcVal \*cols\) \{\n(.*?)\n\}', text, re.S)
    if not fns: sys.exit(f'gen_twins: no decoders in {src}')
    L = ['/- generated by lean/gen_twins.py from the generated C (build/gen/qc_dec.h): the twin of each decoder, the same',
         '   statements in the same order (genStart, one genCol per column, genEnd: Record.lean), each proved equal to',
         '   qc_decode_fast for its shape (decodeFast), which decodeFast_sound proves sound against OP_Column. -/',
         'import Turbo.Record', '', 'namespace Turbo.Record.Generated', 'open Turbo.Record', '']
    for name, sig, body in fns:
        got = [l.strip() for l in body.split('\n') if l.strip()]
        want = HEAD + sum(([GUARD] + block(c, k) for k, c in enumerate(sig)), []) + [END]
        if got != want:
            bad = next((i for i, (a, b) in enumerate(zip(got, want)) if a != b), min(len(got), len(want)))
            sys.exit(f'gen_twins: {name} is not the shape the twins describe (statement {bad}: '
                     f'{got[bad] if bad < len(got) else "<end>"!r}, expected {want[bad] if bad < len(want) else "<end>"!r})')
        L.append(f'def {name} (b : Bytes) : Option (List RV) :=')
        L.append('  genStart b fun he h d =>')
        for k, c in enumerate(sig):
            L.append(f'  genCol b he .{c} h d fun h d v{k} =>')
        L.append('  genEnd b he h d [' + ', '.join(f'v{k}' for k in range(len(sig))) + ']')
        shape = '[' + ', '.join('.' + c for c in sig) + ']'
        L.append(f'theorem {name}_eq (b : Bytes) : {name} b = decodeFast b {shape} := by rw [decodeFast_chain]; rfl')
        L.append('')
    L.append(f'/-- The decoders checked: {len(fns)}. -/')
    L.append(f'def count : Nat := {len(fns)}')
    L.append('')
    L.append('end Turbo.Record.Generated')
    open(out, 'w').write('\n'.join(L) + '\n')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
